/// Pasteboard type identifiers that mark content as private.
///
/// `NSPasteboard` has no public "exclude from history" flag. The conventions
/// below are the de facto contract implemented by password managers and honored
/// by clipboard managers on macOS: a pasteboard item carrying one of these
/// types must not be recorded.
public enum PasteboardPrivacy {
    public static let confidentialTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "com.agilebits.onepassword-otp",
        "de.petermaurer.TransientPasteboardType",
        "com.typeit4me.clipping",
        "Pasteboard generator type",
        "com.jetbrains.pasteboard.security",
    ]

    private static let normalizedTypes = Set(confidentialTypes.map { $0.lowercased() })

    public static func isConfidential(type: String) -> Bool {
        normalizedTypes.contains(type.lowercased())
    }

    public static func containsConfidentialType<S: Sequence>(_ types: S) -> Bool where S.Element == String {
        types.contains(where: isConfidential(type:))
    }
}

/// Decides whether a clipboard change may be captured, given the app that
/// produced it. Pure logic, so the tests can exercise every rule headlessly.
public struct CaptureExclusionPolicy: Equatable, Sendable {
    public var rules: [CaptureExclusionRule]

    public init(rules: [CaptureExclusionRule]) {
        self.rules = rules
    }

    public init(preferences: Preferences) {
        self.rules = preferences.captureExclusions
    }

    /// The first enabled rule matching the source bundle identifier.
    public func excludedRule(bundleIdentifier: String?) -> CaptureExclusionRule? {
        guard let raw = bundleIdentifier?.trimmingCharacters(in: .whitespacesAndNewlines),
              !raw.isEmpty
        else {
            return nil
        }
        return rules.first { rule in
            rule.isEnabled
                && rule.bundleIdentifier.caseInsensitiveCompare(raw) == .orderedSame
        }
    }

    public func shouldSkip(bundleIdentifier: String?) -> Bool {
        excludedRule(bundleIdentifier: bundleIdentifier) != nil
    }
}
