// Capture-level privacy: apps whose clipboard content is never recorded, and
// the pasteboard type markers that ask clipboard managers to leave a change
// out of history.
//
// The rule is applied before the pasteboard is read, so an excluded capture
// never reaches SQLite or a sync folder, and the skip log names only the rule.
// AppKit-free: the pasteboard side lives in `app/PasteboardBridge.swift` and the
// source app is supplied by the watcher.

import Foundation

/// One app whose clipboard content is ignored.
public struct CaptureExclusionRule: Codable, Equatable, Identifiable, Sendable {
    /// Bundle identifier used for matching, for example `com.1password.1password`.
    public var bundleIdentifier: String
    /// Readable label shown in Preferences, for example `1Password`.
    public var name: String
    /// A disabled rule stays in the list but captures from the app normally.
    public var isEnabled: Bool

    /// Stable identity for SwiftUI and preference diffs. Bundle identifiers are
    /// case-insensitive for comparison even though the stored spelling is kept.
    public var id: String { bundleIdentifier.lowercased() }

    public init(
        bundleIdentifier: String,
        name: String,
        isEnabled: Bool = true
    ) {
        self.bundleIdentifier = bundleIdentifier
        self.name = name
        self.isEnabled = isEnabled
    }

    /// Trims the fields and drops a rule with no usable bundle identifier.
    public func normalized() -> CaptureExclusionRule? {
        let identifier = bundleIdentifier.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !identifier.isEmpty else { return nil }
        let label = name.trimmingCharacters(in: .whitespacesAndNewlines)
        return CaptureExclusionRule(
            bundleIdentifier: identifier,
            name: label.isEmpty ? identifier : label,
            isEnabled: isEnabled
        )
    }
}

/// The app a clipboard change came from, as shown in Preferences.
public struct SourceApplication: Equatable, Sendable {
    public var bundleIdentifier: String
    public var name: String

    public init(bundleIdentifier: String, name: String) {
        self.bundleIdentifier = bundleIdentifier
